use crate::colors::{bold, dim, green};
use crate::paths::{absolute, home_dir};
use anyhow::{Result, bail};
use std::path::{Path, PathBuf};

const SKILL_NAME: &str = "imp";

const SKILL_TARGETS: [(&str, &str); 2] = [
    (".agents/skills", "Codex, Cursor"),
    (".claude/skills", "Claude Code, Cursor"),
];

pub const AGENT_SKILL: &str = include_str!("../templates/agent-skill.md");

pub struct SkillRoot {
    pub dir: PathBuf,
    pub reason: &'static str,
    pub global: bool,
}

pub fn find_skill_root(start: &Path, home: Option<&Path>) -> Result<SkillRoot> {
    let home_dir = home.map(absolute);
    let mut dir = absolute(start);
    loop {
        if dir.join(".git").exists() {
            return Ok(SkillRoot {
                dir,
                reason: "git root",
                global: false,
            });
        }
        if Some(&dir) == home_dir.as_ref() || !dir.pop() {
            break;
        }
    }
    let Some(home_dir) = home_dir else {
        bail!("not in a git repository and the home folder is unknown - set HOME")
    };
    Ok(SkillRoot {
        dir: home_dir,
        reason: "not in a git repository",
        global: true,
    })
}

/// Marks a skill file written by `imp skill --init`. `imp update` rewrites
/// only the files that still have it.
const MARKER: &str = "<!-- Generated by `imp skill --init`";

/// The skill with the marker line right after the front matter, where the
/// agents still read the front matter.
pub fn generated_skill() -> String {
    let marker = format!(
        "{MARKER}. `imp update` rewrites this file; delete this line to keep your own changes. -->\n"
    );
    match AGENT_SKILL
        .strip_prefix("---\n")
        .and_then(|rest| rest.find("\n---\n"))
    {
        Some(end) => {
            let split = "---\n".len() + end + "\n---\n".len();
            format!("{}{marker}{}", &AGENT_SKILL[..split], &AGENT_SKILL[split..])
        }
        None => format!("{marker}{AGENT_SKILL}"),
    }
}

fn is_generated(text: &str) -> bool {
    text.lines().any(|line| line.starts_with(MARKER))
}

fn skill_files(root: &Path) -> Vec<PathBuf> {
    SKILL_TARGETS
        .iter()
        .map(|(dir, _)| {
            // Join each part so a printed path uses one separator on Windows.
            let mut path = root.to_path_buf();
            path.extend(dir.split('/'));
            path.join(SKILL_NAME).join("SKILL.md")
        })
        .collect()
}

/// Writes the skill for each agent, replacing the files that exist. Returns
/// the paths, the agents and whether the file existed.
pub fn install_agent_skill(root: &SkillRoot) -> Result<Vec<(String, &'static str, bool)>> {
    let content = generated_skill();
    let mut written = Vec::new();
    for (dir, read_by) in SKILL_TARGETS {
        let path = format!("{dir}/{SKILL_NAME}/SKILL.md");
        let file = root.dir.join(&path);
        let existed = file.exists();
        std::fs::create_dir_all(file.parent().unwrap())?;
        std::fs::write(&file, &content)?;
        written.push((path, read_by, existed));
    }
    Ok(written)
}

pub fn init_agent_skill() -> Result<()> {
    let root = find_skill_root(&crate::paths::cwd(), home_dir().as_deref())?;
    let files = install_agent_skill(&root)?;
    let action = if files.iter().all(|(_, _, existed)| *existed) {
        "Updated"
    } else {
        "Created"
    };
    let created = if root.global {
        format!("{action} the imp skill for all projects")
    } else {
        format!("{action} the imp skill")
    };
    println!(
        "{} in {} ({})\n",
        green(created),
        root.dir.display(),
        root.reason
    );
    let width = files
        .iter()
        .map(|(path, _, _)| path.len())
        .max()
        .unwrap_or(0);
    for (path, read_by, _) in &files {
        println!("  {}  {}", bold(format!("{path:<width$}")), dim(read_by));
    }
    println!("\nTry: /imp add a settings page with a theme switch");
    Ok(())
}

/// The skill files under `root` that still have the marker.
fn generated_files(root: &Path) -> Vec<PathBuf> {
    skill_files(root)
        .into_iter()
        .filter(|file| std::fs::read_to_string(file).is_ok_and(|text| is_generated(&text)))
        .collect()
}

/// Rewrites the skills that `imp skill --init` wrote, when they still have
/// the marker: the ones at the git root of `cwd`, else (no repository, or no
/// generated skill in it) the ones in the home folder. Returns the lines to
/// print: the files it changed. `imp update` runs it with the version it pins
/// (`imp skill --refresh`), so the skill of that version is written.
pub fn refresh(cwd: &Path, home: Option<&Path>) -> Vec<String> {
    let files = find_skill_root(cwd, home)
        .ok()
        .filter(|root| !root.global)
        .map(|root| generated_files(&root.dir))
        .filter(|files| !files.is_empty())
        .or_else(|| home.map(|home| generated_files(&absolute(home))))
        .unwrap_or_default();

    let content = generated_skill();
    let mut updated = Vec::new();
    let mut errors = Vec::new();
    for file in files {
        if std::fs::read_to_string(&file).is_ok_and(|text| text == content) {
            continue;
        }
        match std::fs::write(&file, &content) {
            Ok(()) => updated.push(format!("  {}", file.display())),
            Err(error) => errors.push(format!(
                "cannot update the skill {} - {error}",
                file.display()
            )),
        }
    }
    let mut lines = Vec::new();
    if !updated.is_empty() {
        lines.push("Updated skills:".to_string());
        lines.extend(updated);
    }
    lines.extend(errors);
    lines
}

/// `imp skill --refresh`.
pub fn refresh_agent_skills() -> Result<()> {
    for line in refresh(&crate::paths::cwd(), home_dir().as_deref()) {
        println!("{line}");
    }
    Ok(())
}
