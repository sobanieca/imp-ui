import { buildTokens } from '../../lib/src/theme.js'
import { paletteTokens, SEMANTIC_ALIASES } from '../../lib/src/theme_colors.js'

export const themeFromDraft = (themeName, draft, mode) => ({
  name: `${themeName} (${mode})`,
  colorScheme: mode,
  tokens: buildTokens({
    ...draft[mode],
    radius: draft.radius,
    shadow: draft.shadow,
    colorScheme: mode,
  }),
})

const quote = (value) => {
  const text = String(value)
  return text.includes("'") ? `"${text.replaceAll('"', '\\"')}"` : `'${text}'`
}

const entries = (tokens, indent) =>
  Object.entries(tokens)
    .map(([name, value]) => `${indent}${quote(name)}: ${quote(value)},`)
    .join('\n')

const themeSource = (themeName, draft, mode) => {
  const { tokens } = themeFromDraft(themeName, draft, mode)
  const palette = paletteTokens()
  const own = Object.fromEntries(
    Object.entries(tokens).filter(([name]) =>
      !Object.hasOwn(palette, name) && !Object.hasOwn(SEMANTIC_ALIASES, name)
    ),
  )
  const aliases = Object.entries(SEMANTIC_ALIASES)
    .map(([name, source]) => `    ${quote(name)}: palette[${quote(`color-${source}`)}],`)
    .join('\n')
  return `export const ${mode} = {
  name: ${quote(`${themeName}-${mode}`)},
  colorScheme: ${quote(mode)},
  tokens: {
    ...palette,
${aliases}
${entries(own, '    ')}
  },
}`
}

export const themeFileSource = (themeName, draft) =>
  `// Generated by the imp theme editor.
// Every value below is a plain CSS value - edit any of them by hand.
// The palette is shared by both themes; the editor never rewrites it.
const palette = {
${entries(paletteTokens(), '  ')}
}

${themeSource(themeName, draft, 'light')}

${themeSource(themeName, draft, 'dark')}

export default light
`
