import { buildTokens } from '../../lib/src/theme.js'
import { paletteTokens, SEMANTIC_SOURCES } from '../../lib/src/theme-colors.js'

export const FONT_TOKENS = ['font-family', 'font-family-mono']

const fontTokens = (draft) => ({
  'font-family': draft.font,
  'font-family-mono': draft.fontMono,
})

const KNOB_TOKEN_PREFIXES = ['color-', 'radius-', 'shadow-', 'font-family']

export const keptTokens = (tokens) =>
  Object.fromEntries(
    Object.entries(tokens).filter(([name]) =>
      !KNOB_TOKEN_PREFIXES.some((prefix) => name.startsWith(prefix))
    ),
  )

export const themeFromDraft = (themeName, draft, mode) => ({
  name: `${themeName} (${mode})`,
  tokens: buildTokens({
    ...draft[mode],
    radius: draft.radius,
    shadow: draft.shadow,
    mode,
    overrides: { ...draft.kept, ...fontTokens(draft) },
  }),
})

const quote = (value) => {
  const text = String(value)
  return text.includes("'") ? `"${text.replaceAll('"', '\\"')}"` : `'${text}'`
}

const entries = (tokens, indent) =>
  Object.entries(tokens)
    .map(([name, value]) => `${indent}${quote(name)}: ${quote(value)},`)
    .join('\n')

const themeSource = (themeName, draft, mode) => {
  const { tokens } = themeFromDraft(themeName, draft, mode)
  const palette = paletteTokens()
  const own = Object.fromEntries(
    Object.entries(tokens).filter(([name]) =>
      !Object.hasOwn(palette, name) && !Object.hasOwn(SEMANTIC_SOURCES, name) &&
      !FONT_TOKENS.includes(name)
    ),
  )
  const aliases = Object.entries(SEMANTIC_SOURCES)
    .map(([name, source]) => `    ${quote(name)}: palette[${quote(`color-${source}`)}],`)
    .join('\n')
  return `export const ${mode} = {
  name: ${quote(`${themeName}-${mode}`)},
  tokens: {
    ...fonts,
    ...palette,
${aliases}
${entries(own, '    ')}
  },
}`
}

export const themeFileSource = (themeName, draft) =>
  `// Generated by the imp theme editor.
// Every value below is a plain CSS value - edit any of them by hand.
// The fonts and the palette are shared by both themes; the editor never rewrites the palette.
// Load a web font named here with a <link> in index.html, at the weights of font-weight-normal
// and font-weight-bold.
const fonts = {
${entries(fontTokens(draft), '  ')}
}

const palette = {
${entries(paletteTokens(), '  ')}
}

${themeSource(themeName, draft, 'light')}

${themeSource(themeName, draft, 'dark')}

export default light
`
