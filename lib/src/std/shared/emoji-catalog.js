const VARIATION_SELECTOR = /\uFE0F/g

const glyphOf = (code) =>
  String.fromCodePoint(...code.split('-').map((part) => Number.parseInt(part, 16)))

export const emojiKey = (emoji) => emoji.replace(VARIATION_SELECTOR, '')

const entryOf = ([code, name, keywords]) => ({
  emoji: glyphOf(code),
  name,
  terms: `${name} ${keywords}`,
})

let categories = null

export const emojiCategories = () =>
  (categories ??= Object.entries(EMOJI_CATEGORIES).map(([id, rows]) => ({
    id,
    entries: rows.map(entryOf),
  })))

let byKey = null

export const describeEmoji = (emoji) => {
  byKey ??= new Map(
    emojiCategories().flatMap(({ entries }) =>
      entries.map((entry) => [emojiKey(entry.emoji), entry]),
    ),
  )
  return byKey.get(emojiKey(emoji)) ?? null
}
