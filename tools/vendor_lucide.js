import { fromFileUrl } from '@std/path'

const VERSION = '1.38.0'

const TARGET = fromFileUrl(new URL('../lib/src/icons/lucide_icons.js', import.meta.url))

const NOTICE = `/*!
 * Lucide ${VERSION} - https://lucide.dev
 * Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as part of Feather (MIT).
 * All other copyright (c) for Lucide are held by Lucide Contributors 2022 (ISC).
 *
 * Icons only, as their drawing instructions. The artwork is unchanged; imp reshapes each icon
 * into a list of [element, attributes] pairs and renames it from 'user' to 'luUser'.
 */`

const pascalCase = (iconName) =>
  iconName.split('-').map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('')

const quote = (value) => `'${String(value).replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`

const attributes = (values) =>
  Object.entries(values).map(([name, value]) => `${name}: ${quote(value)}`).join(', ')

const declaration = (iconName, nodes) => {
  const drawing = nodes.map(([element, values]) => `[${quote(element)}, { ${attributes(values)} }]`)
  return `export const lu${pascalCase(iconName)} = [${drawing.join(', ')}]`
}

const iconNodes = async () => {
  const module = await import(`npm:lucide-static@${VERSION}/icon-nodes.json`, {
    with: { type: 'json' },
  })
  return Object.entries(module.default).sort(([a], [b]) => a.localeCompare(b))
}

const icons = await iconNodes()
const lines = [
  '// Generated by tools/vendor_lucide.js - do not edit',
  NOTICE,
  '',
  ...icons.map(([iconName, nodes]) => declaration(iconName, nodes)),
  '',
]

await Deno.mkdir(fromFileUrl(new URL('../lib/src/icons/', import.meta.url)), { recursive: true })
await Deno.writeTextFile(TARGET, lines.join('\n'))
const { size } = await Deno.stat(TARGET)
console.error(
  `wrote lib/src/icons/lucide_icons.js - Lucide ${VERSION}, ${icons.length} icons, ` +
    `${Math.round(size / 1024)} kB`,
)
