import { fromFileUrl } from '@std/path'

const VERSION = '5.1.2'

const SOURCE = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v${VERSION}/geojson/`

const DATA_DIR = new URL('../lib/src/std/data/', import.meta.url)

const GRID = 65535

const MAX_LATITUDE = 85.0511

const ROAD_KINDS = ['Major Highway', 'Secondary Highway']

const notice = (what) =>
  `/*!
 * Natural Earth ${VERSION} - https://www.naturalearthdata.com
 * Public domain. No permission is needed and no credit is required.
 *
 * ${what}, projected to Web Mercator and quantized to a
 * ${GRID} x ${GRID} grid. Each shape is a delta-encoded string of that grid.
 */`

const clamp = (value, low, high) => Math.min(high, Math.max(low, value))

const project = ([longitude, latitude]) => {
  const radians = clamp(latitude, -MAX_LATITUDE, MAX_LATITUDE) * Math.PI / 180
  const x = (longitude + 180) / 360
  const y = (1 - Math.log(Math.tan(radians) + 1 / Math.cos(radians)) / Math.PI) / 2
  return [Math.round(clamp(x, 0, 1) * GRID), Math.round(clamp(y, 0, 1) * GRID)]
}

const encodeInteger = (value) => {
  let rest = value < 0 ? ~(value << 1) : value << 1
  let text = ''
  while (rest >= 0x20) {
    text += String.fromCharCode((0x20 | (rest & 0x1f)) + 63)
    rest >>= 5
  }
  return text + String.fromCharCode(rest + 63)
}

const encodePoints = (points) => {
  let text = ''
  let [lastX, lastY] = [0, 0]
  for (const [x, y] of points) {
    text += encodeInteger(x - lastX) + encodeInteger(y - lastY)
    lastX = x
    lastY = y
  }
  return text
}

const quantize = (coordinates) => {
  const points = []
  for (const coordinate of coordinates) {
    const point = project(coordinate)
    const last = points.at(-1)
    if (last && last[0] === point[0] && last[1] === point[1]) continue
    points.push(point)
  }
  return points
}

const quantizeRing = (coordinates) => {
  const points = quantize(coordinates)
  const first = points[0]
  const last = points.at(-1)
  if (points.length > 1 && first[0] === last[0] && first[1] === last[1]) points.pop()
  return points.length >= 3 ? points : null
}

const quantizeLine = (coordinates) => {
  const points = quantize(coordinates)
  return points.length >= 2 ? points : null
}

const ringsOf = (geometry) => {
  const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates
  return polygons.flat().map(quantizeRing).filter(Boolean).map(encodePoints)
}

const linesOf = (geometry) => {
  const lines = geometry.type === 'LineString' ? [geometry.coordinates] : geometry.coordinates
  return lines.map(quantizeLine).filter(Boolean).map(encodePoints)
}

const fetchJson = async (name) => {
  const response = await fetch(`${SOURCE}${name}.geojson`)
  if (!response.ok) throw new Error(`${name}: ${response.status} ${response.statusText}`)
  return response.json()
}

const shapes = (collection) => collection.features.map(({ geometry }) => ringsOf(geometry))

const placeEntries = (places) =>
  places.features
    .map(({ properties, geometry }) => {
      const [x, y] = project(geometry.coordinates)
      return [properties.name.replace(/\s+/g, ' '), x, y, Number(properties.min_zoom.toFixed(1))]
    })
    .sort((a, b) => a[3] - b[3] || a[0].localeCompare(b[0]))

const roadEntries = (roads) =>
  roads.features
    .filter(({ properties }) => ROAD_KINDS.includes(properties.type))
    .flatMap(({ properties, geometry }) =>
      linesOf(geometry).map((line) => [
        ROAD_KINDS.indexOf(properties.type),
        Number(properties.min_zoom.toFixed(1)),
        line,
      ])
    )
    .sort((a, b) => a[1] - b[1] || a[0] - b[0])

const literal = (value) => JSON.stringify(value)

const writeModule = async (file, what, exports) => {
  const lines = [
    '// Generated by tools/vendor-natural-earth.js - do not edit',
    notice(what),
    '',
    `export const WORLD_GRID = ${GRID}`,
    '',
    ...exports.flatMap(([name, value]) => [`export const ${name} = ${literal(value)}`, '']),
  ]
  const target = fromFileUrl(new URL(file, DATA_DIR))
  await Deno.writeTextFile(target, lines.join('\n'))
  const { size } = await Deno.stat(target)
  return Math.round(size / 1024)
}

const writeWorld = async (scale) => {
  const countries = await fetchJson(`ne_${scale}_admin_0_countries`)
  const lakes = await fetchJson(`ne_${scale}_lakes`)
  const places = await fetchJson(`ne_${scale}_populated_places_simple`)
  const entries = placeEntries(places)
  const file = `map-world-${scale}.js`
  const size = await writeModule(file, `The 1:${scale} countries, lakes and populated places`, [
    ['worldCountries', shapes(countries)],
    ['worldLakes', shapes(lakes)],
    ['worldPlaces', entries],
  ])
  console.error(
    `wrote lib/src/std/data/${file} - Natural Earth ${VERSION}, ` +
      `${countries.features.length} countries, ${lakes.features.length} lakes, ` +
      `${entries.length} places, ${size} kB`,
  )
}

const writeRoads = async () => {
  const roads = await fetchJson('ne_10m_roads')
  const entries = roadEntries(roads)
  const file = 'map-roads-10m.js'
  const size = await writeModule(file, 'The 1:10m major and secondary highways', [
    ['worldRoads', entries],
  ])
  console.error(
    `wrote lib/src/std/data/${file} - Natural Earth ${VERSION}, ${entries.length} roads, ${size} kB`,
  )
}

await writeWorld('110m')
await writeWorld('50m')
await writeRoads()
