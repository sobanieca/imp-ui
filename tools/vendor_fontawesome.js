import { fromFileUrl } from '@std/path'

const VERSION = '7.3.1'

const STYLES = [
  { package: 'free-solid-svg-icons', prefix: 'fa' },
  { package: 'free-regular-svg-icons', prefix: 'far' },
  { package: 'free-brands-svg-icons', prefix: 'fab' },
]

const TARGET = fromFileUrl(new URL('../lib/src/icons/fa_icons.js', import.meta.url))

const NOTICE = `/*!
 * Font Awesome Free ${VERSION} by @fontawesome - https://fontawesome.com
 * License - https://fontawesome.com/license/free (Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT License)
 * Copyright 2026 Fonticons, Inc.
 *
 * Icons only, as CC BY 4.0 path data. The artwork is unchanged; imp reshapes each icon
 * into [width, height, path] and renames it by style: fa (solid), far (regular), fab (brands).
 * Brand icons are trademarks of their respective owners, whose use of them imp does not endorse.
 */`

const pascalCase = (iconName) =>
  iconName.split('-').map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('')

const styleIcons = async ({ package: name, prefix }) => {
  const module = await import(`npm:@fortawesome/${name}@${VERSION}`)
  const definitions = new Map()
  for (const [key, value] of Object.entries(module)) {
    if (!key.startsWith('fa') || !value?.iconName || !Array.isArray(value.icon)) continue
    const exportName = `${prefix}${key.slice('fa'.length)}`
    const found = definitions.get(value)
    if (found) found.aliases.push(exportName)
    else definitions.set(value, { definition: value, canonical: exportName, aliases: [] })
  }
  return [...definitions.values()].map((entry) => {
    const expected = `${prefix}${pascalCase(entry.definition.iconName)}`
    const names = [entry.canonical, ...entry.aliases]
    if (!names.includes(expected)) {
      throw new Error(`${name}: '${entry.definition.iconName}' exports no ${expected}`)
    }
    return {
      canonical: expected,
      aliases: names.filter((alias) => alias !== expected).sort(),
      icon: entry.definition.icon,
    }
  }).sort((a, b) => a.canonical.localeCompare(b.canonical))
}

const declarations = (icons) =>
  icons.flatMap(({ canonical, aliases, icon }) => [
    `export const ${canonical} = [${icon[0]}, ${icon[1]}, '${icon[4]}']`,
    ...aliases.map((alias) => `export const ${alias} = ${canonical}`),
  ])

const lines = ['// Generated by tools/vendor_fontawesome.js - do not edit', NOTICE, '']
let canonicalCount = 0
let aliasCount = 0
for (const style of STYLES) {
  const icons = await styleIcons(style)
  canonicalCount += icons.length
  aliasCount += icons.reduce((total, { aliases }) => total + aliases.length, 0)
  lines.push(...declarations(icons), '')
}

await Deno.mkdir(fromFileUrl(new URL('../lib/src/icons/', import.meta.url)), { recursive: true })
await Deno.writeTextFile(TARGET, lines.join('\n'))
const { size } = await Deno.stat(TARGET)
console.error(
  `wrote lib/src/icons/fa_icons.js - Font Awesome Free ${VERSION}, ` +
    `${canonicalCount} icons and ${aliasCount} aliases, ${Math.round(size / 1024)} kB`,
)
